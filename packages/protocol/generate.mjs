#!/usr/bin/env node
// Generates C# and TypeScript protocol models from schema/protocol.schema.json.
// Usage: node generate.mjs [--check]   (--check fails on drift instead of writing)
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const schema = JSON.parse(readFileSync(join(here, 'schema/protocol.schema.json'), 'utf8'));
const pascal = (s) => s.split('_').map((p) => p[0].toUpperCase() + p.slice(1)).join('');
const prim = { string: ['string', 'string'], int32: ['int', 'number'], int64: ['long', 'Int64String'], bool: ['bool', 'boolean'], json: ['System.Text.Json.JsonElement', 'unknown'] };

function parse(spec) {
  let optional = false, array = false, base = spec;
  if (base.endsWith('?')) { optional = true; base = base.slice(0, -1); }
  if (base.endsWith('[]')) { array = true; base = base.slice(0, -2); }
  const known = prim[base] || schema.enums[base] || schema.types[base];
  if (!known) throw new Error(`Unknown type '${spec}'`);
  return { optional, array, base };
}

function csType(spec) {
  const { optional, array, base } = parse(spec);
  let t = prim[base] ? prim[base][0] : base;
  if (array) t = `IReadOnlyList<${t}>`;
  return optional ? `${t}?` : t;
}
function tsType(spec) {
  const { array, base } = parse(spec);
  let t = prim[base] ? prim[base][1] : base;
  return array ? `${t}[]` : t;
}

const header = '// <auto-generated/> Generated by packages/protocol/generate.mjs from schema/protocol.schema.json. Do not edit.';
let cs = `${header}\n#nullable enable\nusing System.Text.Json.Serialization;\n\nnamespace OrbitDrive.Protocol;\n\npublic static class ProtocolInfo\n{\n    public const int Version = ${schema.protocolVersion};\n    public const int MinVersion = ${schema.minProtocolVersion};\n}\n\npublic static class Actions\n{\n${schema.actions.map((a) => `    public const string ${pascal(a)} = "${a}";`).join('\n')}\n    public static readonly IReadOnlySet<string> All = new HashSet<string> { ${schema.actions.map((a) => `"${a}"`).join(', ')} };\n}\n`;
for (const [name, values] of Object.entries(schema.enums)) {
  cs += `\n[JsonConverter(typeof(JsonStringEnumConverter<${name}>))]\npublic enum ${name}\n{\n${values.map((v) => `    [JsonStringEnumMemberName("${v}")] ${pascal(v)},`).join('\n')}\n}\n`;
}
for (const [name, fields] of Object.entries(schema.types)) {
  cs += `\npublic sealed record ${name}\n{\n`;
  for (const [field, spec] of Object.entries(fields)) {
    const { optional, base } = parse(spec);
    const conv = base === 'int64' ? (optional ? '[JsonConverter(typeof(NullableInt64StringConverter))] ' : '[JsonConverter(typeof(Int64StringConverter))] ') : '';
    const req = optional ? '' : 'required ';
    cs += `    [JsonPropertyName("${field}")] ${conv}public ${req}${csType(spec)} ${field[0].toUpperCase() + field.slice(1)} { get; init; }\n`;
  }
  cs += `}\n`;
}

let ts = `${header}\n/* eslint-disable */\n/** Exact 64-bit integer encoded as a decimal string (never a JSON number). */\nexport type Int64String = string;\n\nexport const PROTOCOL_VERSION = ${schema.protocolVersion};\nexport const MIN_PROTOCOL_VERSION = ${schema.minProtocolVersion};\nexport const ACTIONS = ${JSON.stringify(schema.actions)} as const;\n`;
for (const [name, values] of Object.entries(schema.enums)) {
  ts += `\nexport type ${name} = ${values.map((v) => `'${v}'`).join(' | ')};\n`;
}
for (const [name, fields] of Object.entries(schema.types)) {
  ts += `\nexport interface ${name} {\n`;
  for (const [field, spec] of Object.entries(fields)) {
    const { optional } = parse(spec);
    ts += `  ${field}${optional ? '?' : ''}: ${tsType(spec)}${optional ? ' | null' : ''};\n`;
  }
  ts += `}\n`;
}
ts += `\nexport interface ProtocolTypeMap {\n${Object.keys(schema.types).map((n) => `  ${n}: ${n};`).join('\n')}\n}\n`;
ts += `\nexport const SCHEMA = ${JSON.stringify({ enums: schema.enums, types: schema.types }, null, 2)} as const;\n`;

const outputs = [
  [join(here, 'generated/csharp/Protocol.g.cs'), cs],
  [join(here, 'generated/ts/protocol.g.ts'), ts],
];
const check = process.argv.includes('--check');
let drift = false;
for (const [path, content] of outputs) {
  if (check) {
    if (!existsSync(path) || readFileSync(path, 'utf8') !== content) { console.error(`DRIFT: ${path} is stale; run node packages/protocol/generate.mjs`); drift = true; }
  } else {
    writeFileSync(path, content);
    console.log(`wrote ${path}`);
  }
}
if (drift) process.exit(1);
if (check) console.log('protocol models are up to date');
