#!/usr/bin/env node
// Builds a Windows release CANDIDATE (D12). Nothing is published, signed or deployed.
//   node tools/release/release-candidate.mjs --version 0.1.0 --commit <40-hex sha> --out artifacts/release [--run-id N] [--skip-desktop]
// Output: OrbitDrive-<version>-win-x64.zip, SHA256SUMS, THIRD_PARTY_NOTICES.md (inside the zip and beside it), release-manifest.json.
// The script verifies its own output (zip readable, every checksum recomputed) and exits non-zero on any mismatch.
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync, mkdtempSync } from 'node:fs';
import { tmpdir, platform, release, arch } from 'node:os';
import { join, relative, dirname, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { writeZip, checksumFile, parseChecksums, sha256, buildManifest } from './release-lib.mjs';
import { readZip } from '../../tests/integration/harness.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const arg = (name, fallback) => { const i = process.argv.indexOf(`--${name}`); return i < 0 ? fallback : process.argv[i + 1]; };
const version = arg('version'), commit = arg('commit'), out = resolve(arg('out', join(root, 'artifacts', 'release')));
const skipDesktop = process.argv.includes('--skip-desktop');
if (!version || !commit) { console.error('usage: release-candidate.mjs --version X.Y.Z --commit <sha> [--out dir] [--run-id N] [--skip-desktop]'); process.exit(2); }
if (!skipDesktop && platform() !== 'win32') { console.error('The WPF console builds on Windows only. Use --skip-desktop for a partial (non-release) build.'); process.exit(2); }

const run = (cmd, args) => execFileSync(cmd, args, { stdio: 'inherit', cwd: root, shell: platform() === 'win32' });
const staging = mkdtempSync(join(tmpdir(), 'orbit-rc-'));
const publish = (project) => run('dotnet', ['publish', `apps/desktop/${project}`, '-c', 'Release', '-r', 'win-x64', '--self-contained', 'true', '-o', staging,
  `-p:Version=${version}`, `-p:InformationalVersion=${version}+${commit.slice(0, 12)}`, '-p:DebugType=none', '-p:DebugSymbols=false', '-p:EnableWindowsTargeting=true']);
publish('OrbitDrive.Agent');
publish('OrbitDrive.ThumbnailHelper');
if (!skipDesktop) publish('OrbitDrive.Desktop');

const walk = (dir) => readdirSync(dir, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(join(dir, e.name)) : [join(dir, e.name)]));
// Debug symbols (.pdb) are not part of the artifact: they are large, tell an attacker nothing useful the binaries do not, and the support bundle does not need them.
const entries = walk(staging).filter((f) => !/\.pdb$/i.test(f)).map((f) => ({ name: `OrbitDrive/${relative(staging, f).split(sep).join('/')}`, data: readFileSync(f) }));
for (const required of ['OrbitDrive/orbitdrive-agent.exe', 'OrbitDrive/OrbitDrive.ThumbnailHelper.exe', ...(skipDesktop ? [] : ['OrbitDrive/OrbitDrive.exe'])])
  if (!entries.some((e) => e.name === required)) throw new Error(`The build is missing ${required}`);

// Third-party notices: the .NET runtime's own notice file (shipped with the self-contained runtime) plus the licence of every NuGet package that was restored for these projects.
const nugetRoot = process.env.NUGET_PACKAGES ?? join(process.env.USERPROFILE ?? process.env.HOME ?? '', '.nuget', 'packages');
const props = readFileSync(join(root, 'Directory.Packages.props'), 'utf8');
const shipped = ['SkiaSharp', 'SkiaSharp.NativeAssets.Win32'];
const versionOf = (id) => new RegExp(`<PackageVersion Include="${id.replace(/\./g, '\\.')}" Version="([^"]+)"`).exec(props)?.[1];
let notices = `# Third-party notices\n\nOrbitDrive ${version} (${commit.slice(0, 12)}). Generated by tools/release/release-candidate.mjs from the packages that were actually restored for this build.\nOrbitDrive's own licence has not been chosen by the owner yet; this file covers only third-party components.\n`;
const runtimeNotice = entries.find((e) => /(^|\/)THIRD-PARTY-NOTICES\.TXT$/i.test(e.name))
  ?? (() => { const f = existsSync(nugetRoot) ? walk(join(nugetRoot, 'microsoft.netcore.app.runtime.win-x64')).find((p) => /THIRD-PARTY-NOTICES\.TXT$/i.test(p)) : null; return f ? { data: readFileSync(f) } : null; })();
if (!runtimeNotice) throw new Error('The .NET runtime notice file was not found; refusing to ship without third-party notices.');
notices += `\n## .NET runtime (self-contained)\nMicrosoft .NET is licensed under the MIT licence. Its full third-party notice list follows.\n\n\`\`\`\n${runtimeNotice.data.toString('utf8')}\n\`\`\`\n`;
for (const id of shipped) {
  const v = versionOf(id), dir = join(nugetRoot, id.toLowerCase(), v ?? '');
  if (!v || !existsSync(dir)) throw new Error(`Package ${id} ${v} was not restored; cannot write its notice.`);
  const nuspec = readFileSync(readdirSync(dir).map((f) => join(dir, f)).find((f) => f.endsWith('.nuspec')), 'utf8');
  const license = /<license type="expression">([^<]+)<\/license>/.exec(nuspec)?.[1] ?? /<licenseUrl>([^<]+)<\/licenseUrl>/.exec(nuspec)?.[1];
  if (!license) throw new Error(`No licence declared by ${id} ${v}`);
  const licenseFile = readdirSync(dir).find((f) => /^licen[sc]e/i.test(f));
  notices += `\n## ${id} ${v}\nLicence: ${license}\n${licenseFile ? `\n\`\`\`\n${readFileSync(join(dir, licenseFile), 'utf8')}\n\`\`\`\n` : ''}`;
}
entries.push({ name: 'OrbitDrive/THIRD_PARTY_NOTICES.md', data: Buffer.from(notices) });

// Owner documentation travels with the artifact.
for (const doc of ['docs/release/INSTALL.md', 'docs/release/SUPPORT_MATRIX.md', 'docs/release/TROUBLESHOOTING.md'])
  entries.push({ name: `OrbitDrive/docs/${doc.split('/').pop()}`, data: readFileSync(join(root, doc)) });

mkdirSync(out, { recursive: true });
const zipName = `OrbitDrive-${version}-win-x64.zip`;
const zip = writeZip(entries);
writeFileSync(join(out, zipName), zip);
writeFileSync(join(out, 'THIRD_PARTY_NOTICES.md'), notices);
const files = [{ name: zipName, data: zip }, { name: 'THIRD_PARTY_NOTICES.md', data: Buffer.from(notices) }];
writeFileSync(join(out, 'SHA256SUMS'), checksumFile(files));
const manifest = buildManifest({
  version, commit, runId: arg('run-id', null),
  builder: { os: `${platform()} ${release()} ${arch()}`, node: process.version, dotnet: execFileSync('dotnet', ['--version'], { encoding: 'utf8', shell: platform() === 'win32' }).trim(), imageVersion: process.env.ImageVersion ?? null },
  artifacts: files.map((f) => ({ name: f.name, size: f.data.length, sha256: sha256(f.data) })),
});
manifest.contents = entries.map((e) => ({ name: e.name, size: e.data.length, sha256: sha256(e.data) })).sort((a, b) => (a.name < b.name ? -1 : 1));
manifest.partial = skipDesktop;
writeFileSync(join(out, 'release-manifest.json'), JSON.stringify(manifest, null, 2) + '\n');

// Self-verification from the files on disk (what the owner will check): checksums, readable zip, every entry's CRC and recorded hash.
const sums = parseChecksums(readFileSync(join(out, 'SHA256SUMS'), 'utf8'));
for (const f of files) if (sums.get(f.name) !== sha256(readFileSync(join(out, f.name)))) throw new Error(`Checksum mismatch for ${f.name}`);
for (const e of readZip(readFileSync(join(out, zipName)))) { const want = manifest.contents.find((c) => c.name === e.name); if (!want || want.sha256 !== sha256(e.data())) throw new Error(`Archive entry differs from manifest: ${e.name}`); }
console.log(`Release candidate ${version} (${commit.slice(0, 12)}) written to ${out}${skipDesktop ? ' [PARTIAL: no WPF console]' : ''}`);
console.log(`${zipName}: ${zip.length} bytes, sha256 ${sha256(zip)}`);
